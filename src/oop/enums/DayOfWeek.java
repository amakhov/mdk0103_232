package oop.enums;

/*
Перечисляемый тип enum
- нужен для храниня множества значений - но не любого, а ограниченного.
enum (перечисления) - набор логически связанный констант
-каждый элемент перечисления - final, static
-в перечисление нельзя добавить элемент, и удалить элемент
 */
public enum DayOfWeek {
    // элементы перечисления, экземпляры (объекты)
    MONDAY,
    Вторник,
    WEDNESDAY,
    THURSDAY,
    FRIDAY,
    SATURDAY,
    SUNDAY
}
